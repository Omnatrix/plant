def _clean(s: str) -> str:
    """Normalize whitespace and punctuation for resilient matching."""
    return re.sub(r'\s+', ' ', str(s).strip())

# Pre-normalized dictionary for instant O(1) lookup
_CLEAN_TRANSLATIONS = {_clean(k): v for k, v in UI_TRANSLATIONS.items()}
LANGUAGES = list(LANG_CODES.keys())


def get_ui_translations(target_lang: str) -> dict[str, str]:
    """Returns all pre-computed UI translations for a given language."""
    if target_lang == "English":
        return {k: k for k in UI_TRANSLATIONS.keys()}
    return {
        k: UI_TRANSLATIONS[k].get(target_lang, translate_text(k, target_lang))
        for k in UI_TRANSLATIONS.keys()
    }

@functools.lru_cache(maxsize=4096)
def translate_text(text: str, target_lang: str) -> str:
    """
    Translates text dynamically across all 22 Official Scheduled Indian Languages + English:
    1. Checks the pre-computed dictionary for instant, zero-latency, rate-limit-free UI rendering.
    2. Falls back to deep-translator for dynamic text with caching.
    """
    if not text or target_lang == "English":
        return text

    clean_input = _clean(text)

    # 1. Instant O(1) dictionary lookup
    match = _CLEAN_TRANSLATIONS.get(clean_input)
    if match and target_lang in match:
        return match[target_lang]

    # 2. Try deep_translator fallback for unseen strings
    target_code = LANG_CODES.get(target_lang)
    if target_code and target_code != "en":
        try:
            from deep_translator import GoogleTranslator
            translator = GoogleTranslator(source='auto', target=target_code)
            translated = translator.translate(text)
            if translated:
                return translated
        except Exception:
            pass

    return text
